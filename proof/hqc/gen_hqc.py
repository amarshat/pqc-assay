def avx_isa(p):
    """spec/isabelle/hqc/AVX_P<p>.thy: the AVX2 model's Karatsuba sizes, the multi-way level, Toom (hqc-1
    and hqc-3; the hqc-5 Toom at 256-bit granularity is not proved yet) and vmulA = product mod x^n - 1."""
    c = AVX[p]
    n, N = PARAM_N[p], words(p)
    topf, topn, topm, topkid = c['top']
    tm, tin, tout = c['toom']
    vn, _ = c['vm']
    out = [f'(* GENERATED by proof/hqc/gen_hqc.py for hqc-{p}; do not edit. *)',
           f'theory AVX_P{p}', f'  imports {"AVX_Toom5" if p == 5 else "AVX_Toom"} AVX{p} HQC_P{p}', 'begin', '',
           f'text \\<open>The AVX2 hqc-{p} model: each Karatsuba size multiplies (\\<open>kstep_correct\\<close>), the',
           f'  {topm} level multiplies ({"k3step" if p != 5 else "k5step"}_correct), the Toom-3 product multiplies',
           f'  ({"toom3" if p != 5 else "toom5"}_correct), and vmulA is the product mod x^n - 1.\\<close>', '']
    prev_fact = f'HQC_P{p}.km{c["ladder"][1][1] // 2}_correct'
    for fn, nw in c['ladder'][1:]:
        out += [f'lemma km{nw}_correct: "Pl (L (km{nw} a b)) = Pl (L a) * Pl (L b)"',
                f'  unfolding km{nw}_def', '  apply simp', '  apply ((subst L_coerce, simp)?)',
                '  apply (rule trans[OF kstep_correct])', f'       apply (simp_all add: L_coerce {prev_fact})', '  done', '']
        prev_fact = f'km{nw}_correct'
    step = 'k3step_correct' if p != 5 else 'k5step_correct'
    out += [f'lemma {topm}_correct: "Pl (L ({topm} a b)) = Pl (L a) * Pl (L b)"',
            f'  unfolding {topm}_def', '  apply simp', '  apply ((subst L_coerce, simp)?)',
            f'  apply (rule trans[OF {step}])', f'    apply (simp_all add: L_coerce {prev_fact})', '  done', '']
    if p == 5:   # tm5 = toom5 km320 with no length coercions: the lemma applies as it stands
        out += [f'lemma {tm}_correct: "Pl (L ({tm} a b)) = Pl (L a) * Pl (L b)"',
                f'  unfolding {tm}_def by (rule toom5_correct) (simp add: {topm}_correct)', '']
    else:
        out += [f'lemma {tm}_correct: "Pl (L ({tm} a b)) = Pl (L a) * Pl (L b)"',
                f'  unfolding {tm}_def', '  apply simp', '  apply ((subst L_coerce, simp)?)',
                '  apply (rule trans[OF toom3_correct])', f'    apply (simp_all add: L_coerce {topm}_correct)', '  done', '']
    out += ['context includes cryptol_syntax begin', '',
            'theorem vmulA_correct:',
            f'  assumes "degree (Pl (L a)) < {n}" "degree (Pl (L b)) < {n}"',
            f'  shows "Pl (L (vmulA a b)) = (Pl (L a) * Pl (L b)) mod (monom 1 {n} - 1)"',
            'proof -',
            ] + ([f'  have ta: "Pl (take {tin} (L a)) = Pl (L a)" and tb: "Pl (take {tin} (L b)) = Pl (L b)"',
            '    by (rule Pl_take_eq; simp; rule coeff_eq_0; use assms in simp)+',
            f'  have e: "Pl (L ({tm} (take\'`{{{tin},{vn - tin},[64]}} (coerce_seq_len a)) (take\'`{{{tin},{vn - tin},[64]}} (coerce_seq_len b)))) = Pl (L a) * Pl (L b)"',
            f'    by (simp add: {tm}_correct L_take L_coerce ta tb)'] if vn != tin else
            [f'  have e: "Pl (L ({tm} a b)) = Pl (L a) * Pl (L b)" by (rule {tm}_correct)']) + [
            f'  have deg: "degree (Pl (L a) * Pl (L b)) < 64 * {2 * N}"',
            '    using assms degree_mult_le[of "Pl (L a)" "Pl (L b)"] by simp',
            (f'  have prod: "Pl (take {2 * N} (L ({tm} (take\'`{{{tin},{vn - tin},[64]}} (coerce_seq_len a)) (take\'`{{{tin},{vn - tin},[64]}} (coerce_seq_len b))))) = Pl (L a) * Pl (L b)"'
             if vn != tin else f'  have prod: "Pl (take {2 * N} (L ({tm} a b))) = Pl (L a) * Pl (L b)"'),
            '    apply (subst Pl_take_eq)',
            '      apply simp',
            '     apply (simp add: e, rule coeff_eq_0, use deg in linarith)',
            '    apply (simp add: e)',
            '    done',
            '  show ?thesis',
            '    unfolding vmulA_def',
            '    apply simp',
            '    apply (rule fold_mult_k)',
            '        apply (simp_all add: L_coerce L_take prod assms)',
            '    done',
            'qed', '', 'end', '', 'end']
    return '\n'.join(out) + '\n'


def files():
    for p in PARAM_N:
        yield os.path.join(ROOT, 'model/cryptol/hqc', f'KM{p}.cry'), cry(p)
        yield os.path.join(ROOT, 'proof/hqc', f'karatsuba_{p}.saw'), saw(p)
        yield os.path.join(ROOT, 'spec/isabelle/hqc', f'HQC_P{p}.thy'), isa(p)
        yield os.path.join(ROOT, 'proof/hqc', f'rs_{p}.saw'), rs_saw(p)
        yield os.path.join(ROOT, 'proof/hqc', f'avx_{p}.saw'), avx_saw(p)
        yield os.path.join(ROOT, 'spec/isabelle/hqc', f'AVX_P{p}.thy'), avx_isa(p)


def main():
    check = '--check' in sys.argv
    stale = 0
    for path, text in files():
        if check:
            if not os.path.exists(path) or open(path).read() != text:
                print(f'STALE {os.path.relpath(path, ROOT)}')
                stale = 1
        else:
            with open(path, 'w') as f:
                f.write(text)
    for p in PARAM_N:
        print(f'hqc-{p}: {words(p)} words, sizes {sorted(reached(words(p)))}, '
              f'tmp_buffer {tmp_words(words(p))} of {16 * words(p)} words')
    return stale


if __name__ == '__main__':
    sys.exit(main())
