            f'print "VERIFIED: hqc-{p} AVX2 toom_3_mult == {tm} ({tin} words in, {tout} out)";', '',
            '// vect_mul: the result is written as bytes (memcpy of VEC_N_SIZE_BYTES), so the spec is a byte view.',
            'let vm_spec post = do {', '  for scratch init_global;',
            f'  for [("a1_times_a2",{tout}),("o256",{c["o256"]})] init_global;',
            '  llvm_alloc_global "tmp_reduce";',
