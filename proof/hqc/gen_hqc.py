#!/usr/bin/env python3
"""Generate the HQC vect_mul proofs for hqc-1, hqc-3 and hqc-5.

target/hqc/gf2x.c (HQC v5.0.0) multiplies in GF(2)[x] mod x^n - 1: karatsuba_mul recurses on the
word count, splitting n words into a low half of n/2 and a high half of n - n/2, and calls
schoolbook_mul at 16 words or fewer; vect_mul then folds the 2n-word product with reduce. The
recursion sizes depend on the parameter set, so the Cryptol model and the SAW scripts are generated:

  model/cryptol/hqc/KM<p>.cry   km<s> for every size s the recursion reaches: kmul (pmult) at
                                s <= 16, one Karatsuba level (kstep) over km<s/2>, km<s-s/2> above.
  proof/hqc/karatsuba_<p>.saw   schoolbook_mul(s) == kmul (rme), karatsuba_mul(s) == km<s> for every
                                reached size using the smaller sizes as overrides (z3, children
                                uninterpreted), then vect_mul == fold (km<N> a b).

Every spec has a mutant (X_mut_spec) that must fail. `--check` regenerates into memory and exits 1
if a committed file differs.
"""
import functools, os, sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
PARAM_N = {1: 17669, 3: 35851, 5: 57637}   # target/hqc/hqc-<p>/parameters.h
THR = 16                                   # KARATSUBA_THRESHOLD in gf2x.c


def words(p):
    return (PARAM_N[p] + 63) // 64


@functools.lru_cache(None)
def tmp_words(n):
    """tmp_buffer words karatsuba_mul(n) uses: 8n of its own, then its children's from tmp + 8n.
    A leaf uses none; the spec still asks for one word so the child pointer matches an allocation."""
    if n <= THR:
        return 1
    m = n >> 1
    return 8 * n + max(tmp_words(m), tmp_words(n - m))


def reached(n, acc=None):
    acc = set() if acc is None else acc
    if n not in acc:
        acc.add(n)
        if n > THR:
            reached(n >> 1, acc)
            reached(n - (n >> 1), acc)
    return acc


def cry(p):
    out = [f'// GENERATED by proof/hqc/gen_hqc.py for hqc-{p}; do not edit.',
           f'module KM{p} where', '', 'import GF2X', '']
    for n in sorted(reached(words(p))):
        out.append(f'km{n} : [{n}][64] -> [{n}][64] -> [{2 * n}][64]')
        if n <= THR:
            out.append(f'km{n} = kmul')
        else:
            m = n >> 1
            out.append(f'km{n} = kstep`{{{m},{n - m}}} km{m} km{n - m}')
    return '\n'.join(out) + '\n'


def ops(n, post, karatsuba, tmp):
    s = [f'    rp <- llvm_alloc (llvm_array {2 * n} (llvm_int 64));',
         f'    ap <- llvm_alloc_readonly (llvm_array {n} (llvm_int 64));',
         f'    bp <- llvm_alloc_readonly (llvm_array {n} (llvm_int 64));',
         f'    a <- llvm_fresh_var "a" (llvm_array {n} (llvm_int 64));',
         f'    b <- llvm_fresh_var "b" (llvm_array {n} (llvm_int 64));',
         '    llvm_points_to ap (llvm_term a);',
         '    llvm_points_to bp (llvm_term b);']
    if karatsuba:
        s.append(f'    tp <- llvm_alloc (llvm_array {tmp} (llvm_int 64));')
        s.append(f'    llvm_execute_func [rp, ap, bp, llvm_term {{{{ {n} : [64] }}}}, tp];')
    else:
        s.append(f'    llvm_execute_func [rp, ap, bp, llvm_term {{{{ {n} : [64] }}}}];')
    s.append(f'    llvm_points_to rp (llvm_term {{{{ {post} }}}});')
    return s


MUT_B = '([b@0 ^ 1] # drop`{1} b)'   # the result for a different b: must not match


def saw(p):
    N = words(p)
    sizes = sorted(reached(N))
    out = [f'// GENERATED by proof/hqc/gen_hqc.py for hqc-{p} (n = {PARAM_N[p]}, {N} words); do not edit.',
           '// Run with CRYPTOLPATH=model/cryptol/hqc (make hqc).', '',
           'import "GF2X.cry";', 'import "Fold.cry";', f'import "KM{p}.cry";',
           f'm <- llvm_load_module "../../build/hqc/gf2x_{p}.bc";', '']
    for s in sizes:
        if s > THR:
            continue
        for name, post in ((f'sb_{s}_spec', f'kmul`{{{s}}} a b'), (f'sb_{s}_mut_spec', f'kmul`{{{s}}} a {MUT_B}')):
            out += [f'let {name} = do {{'] + ops(s, post, False, 0) + ['};']
        for name, post in ((f'kara_{s}_spec', f'km{s} a b'), (f'kara_{s}_mut_spec', f'km{s} a {MUT_B}')):
            out += [f'let {name} = do {{'] + ops(s, post, True, 1) + ['};']
        out += [f'sb_{s} <- llvm_verify m "schoolbook_mul" [] false sb_{s}_spec rme;',
                f'fails (llvm_verify m "schoolbook_mul" [] false sb_{s}_mut_spec abc);',
                f'kara_{s} <- llvm_verify m "karatsuba_mul" [sb_{s}] false kara_{s}_spec (w4_unint_z3 ["kmul"]);',
                f'fails (llvm_verify m "karatsuba_mul" [sb_{s}] false kara_{s}_mut_spec (w4_unint_z3 ["kmul"]));',
                f'print "VERIFIED: hqc-{p} schoolbook_mul({s}) == kmul (pmult), karatsuba_mul({s}) == km{s}";', '']
    for n in sizes:
        if n <= THR:
            continue
        kids = sorted({n >> 1, n - (n >> 1)})
        ovs = ', '.join(f'kara_{c}' for c in kids)
        unint = ', '.join(f'"km{c}"' for c in kids)
        for name, post in ((f'kara_{n}_spec', f'km{n} a b'), (f'kara_{n}_mut_spec', f'km{n} a {MUT_B}')):
            out += [f'let {name} = do {{'] + ops(n, post, True, tmp_words(n)) + ['};']
        out += [f'kara_{n} <- llvm_verify m "karatsuba_mul" [{ovs}] false kara_{n}_spec (w4_unint_z3 [{unint}]);',
                f'fails (llvm_verify m "karatsuba_mul" [{ovs}] false kara_{n}_mut_spec (w4_unint_z3 [{unint}]));',
                f'print "VERIFIED: hqc-{p} karatsuba_mul({n}) == km{n}, tmp_buffer within {tmp_words(n)} words";', '']
    for name, n_fold in (('vect_mul_spec', PARAM_N[p]), ('vect_mul_mut_spec', PARAM_N[p] - 1)):
        out += [f'let {name} = do {{',
                f'    op <- llvm_alloc (llvm_array {N} (llvm_int 64));',
                f'    ap <- llvm_alloc_readonly (llvm_array {N} (llvm_int 64));',
                f'    bp <- llvm_alloc_readonly (llvm_array {N} (llvm_int 64));',
                f'    a <- llvm_fresh_var "a" (llvm_array {N} (llvm_int 64));',
                f'    b <- llvm_fresh_var "b" (llvm_array {N} (llvm_int 64));',
                '    llvm_points_to ap (llvm_term a);',
                '    llvm_points_to bp (llvm_term b);',
                '    llvm_execute_func [op, ap, bp];',
                f'    llvm_points_to op (llvm_term {{{{ fold`{{{n_fold}}} (km{N} a b) }}}});',
                '};']
    out += [f'llvm_verify m "vect_mul" [kara_{N}] false vect_mul_spec (w4_unint_z3 ["km{N}"]);',
            f'fails (llvm_verify m "vect_mul" [kara_{N}] false vect_mul_mut_spec (w4_unint_z3 ["km{N}"]));',
            f'print "VERIFIED: hqc-{p} vect_mul == fold`{{{PARAM_N[p]}}} (km{N} a b), for all inputs";',
            f'print "NON-VACUOUS: hqc-{p} mutants (result for a different b; fold at n - 1) are rejected at every size";']
    return '\n'.join(out) + '\n'


def files():
    for p in PARAM_N:
        yield os.path.join(ROOT, 'model/cryptol/hqc', f'KM{p}.cry'), cry(p)
        yield os.path.join(ROOT, 'proof/hqc', f'karatsuba_{p}.saw'), saw(p)


def main():
    check = '--check' in sys.argv
    stale = 0
    for path, text in files():
        if check:
            if not os.path.exists(path) or open(path).read() != text:
                print(f'STALE {os.path.relpath(path, ROOT)}')
                stale = 1
        else:
            with open(path, 'w') as f:
                f.write(text)
    for p in PARAM_N:
        print(f'hqc-{p}: {words(p)} words, sizes {sorted(reached(words(p)))}, '
              f'tmp_buffer {tmp_words(words(p))} of {16 * words(p)} words')
    return stale


if __name__ == '__main__':
    sys.exit(main())
