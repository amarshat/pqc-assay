#!/usr/bin/env python3
"""Generate the hqc-3 and hqc-5 decapsulation models and SAW scripts from the hqc-1 ones (v5.0.0
and v5.1.0).

model/cryptol/hqc-decaps/Decaps1.cry and proof/hqc-decaps/decaps_1.saw are written by hand; this
script substitutes the sizes of hqc-3 and hqc-5 (parameters.h and api.h of HQC v5.0.0) and writes
Decaps3.cry, Decaps5.cry, decaps_3.saw and decaps_5.saw. The CVE-2024-54137 mutant runs stay in the
hqc-1 script only. With --check it fails if the committed files differ from what it would write.
"""
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SIZES = {
    # NB = VEC_N_SIZE_BYTES, VB = VEC_N1N2_SIZE_BYTES, W = VEC_N_SIZE_64, EK, SK, CT, SEC
    1: dict(NB=2209, VB=2208, W=277, EK=2241, SK=2321, CT=4433, SEC=16),
    3: dict(NB=4482, VB=4480, W=561, EK=4514, SK=4602, CT=8978, SEC=24),
    5: dict(NB=7205, VB=7200, W=901, EK=7237, SK=7333, CT=14421, SEC=32),
}


def subst_cry(src, p):
    a, b = SIZES[1], SIZES[p]
    out = src.replace('module Decaps1 where', f'module Decaps{p} where')
    out = out.replace('crypto_kem_dec), hqc-1:', f'crypto_kem_dec), hqc-{p}:')
    for k in ['NB', 'VB', 'W', 'EK', 'SK', 'CT', 'SEC']:
        out = re.sub(rf'^(type {k}\s+= ){a[k]}\b', lambda m: f'{m.group(1)}{b[k]}', out, flags=re.M)
    out = out.replace(f'<- [0 .. {a["SK"] - 1}]', f'<- [0 .. {b["SK"] - 1}]')
    return '// GENERATED by scripts/hqc_decaps_gen.py from Decaps1.cry; do not edit.\n' + out


def subst_saw(src, p):
    a, b = SIZES[1], SIZES[p]
    cut = src.index('// Positive control')
    head = src[:cut]
    # drop the hqc-1-only vect_compare mutant block and the first VERIFIED line, then re-add
    head = head[:head.index('m0 <- llvm_load_module')]
    out = head
    out = out.replace('import "Decaps1.cry";', f'import "Decaps{p}.cry";')
    out = out.replace('crypto_kem_dec, hqc-1:', f'crypto_kem_dec, hqc-{p}:')
    out = out.replace('Decaps1::decaps', f'Decaps{p}::decaps')
    out = out.replace('dec_1.bc', f'dec_{p}.bc')
    out = out.replace(f'"ek" {a["EK"]}', f'"ek" {b["EK"]}')
    out = out.replace(f'"m" {a["SEC"]}', f'"m" {b["SEC"]}')
    out = out.replace(f'"sigma" {a["SEC"]}', f'"sigma" {b["SEC"]}')
    out = out.replace(f'mp <- llvm_alloc (arr {a["SEC"]})', f'mp <- llvm_alloc (arr {b["SEC"]})')
    out = out.replace(f'llvm_array {a["W"]} (llvm_int 64)', f'llvm_array {b["W"]} (llvm_int 64)')
    out = out.replace(f'vect_compare_spec {a["NB"]}', f'vect_compare_spec {b["NB"]}')
    out = out.replace(f'vect_compare_spec {a["VB"]}', f'vect_compare_spec {b["VB"]}')
    out = out.replace(f'"c" {a["CT"]}', f'"c" {b["CT"]}')
    out = out.replace(f'"sk" {a["SK"]}', f'"sk" {b["SK"]}')
    out += (f'print "VERIFIED: hqc-{p} crypto_kem_dec == decaps (implicit rejection); '
            f'vect_compare proved at {b["NB"]}, {b["VB"]}, 16";\n')
    return '// GENERATED by scripts/hqc_decaps_gen.py from decaps_1.saw; do not edit.\n' + out


SIZES51 = {
    # v5.1.0: NB, VB, WU = VEC_N_PKE_WORDS, WV = VEC_N1N2_PKE_WORDS, EK, CT, K = PARAM_K
    1: dict(NB=2209, VB=2208, WU=277, WV=276, EK=2241, CT=4433, K=16),
    3: dict(NB=4482, VB=4480, WU=561, WV=560, EK=4514, CT=8978, K=24),
    5: dict(NB=7205, VB=7200, WU=901, WV=900, EK=7237, CT=14421, K=32),
}


def subst_cry51(src, p):
    a, b = SIZES51[1], SIZES51[p]
    out = src.replace('module DecapsV51_1 where', f'module DecapsV51_{p} where')
    out = out.replace('(hqc_kem_decaps), hqc-1:', f'(hqc_kem_decaps), hqc-{p}:')
    for k in ['NB', 'VB', 'WU', 'WV', 'EK', 'CT', 'K']:
        out = re.sub(rf'^(type {k}\s+= ){a[k]}\b', lambda m: f'{m.group(1)}{b[k]}', out, flags=re.M)
    if b['K'] == 32:
        # both squeezes are 32 bytes: sigma comes from the same xofOut32 as the PKE seed
        out = out.replace('sigmaOf dk = xofOutK (xofNext32 (xofInit dk))',
                          'sigmaOf dk = xofOut32 (xofNext32 (xofInit dk))  // PARAM_K = SEED_BYTES')
    return '// GENERATED by scripts/hqc_decaps_gen.py from DecapsV51_1.cry; do not edit.\n' + out


def subst_saw51(src, p):
    a, b = SIZES51[1], SIZES51[p]
    out = src[:src.index('// Positive control')]
    out = out.replace('import "DecapsV51_1.cry";', f'import "DecapsV51_{p}.cry";')
    out = out.replace('hqc_kem_decaps, hqc-1:', f'hqc_kem_decaps, hqc-{p}:')
    out = out.replace('DecapsV51_1::decaps', f'DecapsV51_{p}::decaps')
    out = out.replace('dec_1.bc', f'dec_{p}.bc')
    out = out.replace(f'llvm_term {{{{ {a["K"]} : [8] }}}}', f'llvm_term {{{{ {b["K"]} : [8] }}}}')
    out = out.replace(f'mp <- llvm_alloc (arr {a["K"]})', f'mp <- llvm_alloc (arr {b["K"]})')
    out = out.replace(f'"m" {a["K"]}', f'"m" {b["K"]}')
    out = out.replace(f'"sigma" {a["K"]}', f'"sigma" {b["K"]}')
    out = out.replace(f'(xof_get_spec {a["K"]})', f'(xof_get_spec {b["K"]})')
    out = out.replace(f'"ek" {a["EK"]}', f'"ek" {b["EK"]}')
    out = out.replace(f'(arr {a["EK"]})', f'(arr {b["EK"]})')
    out = out.replace(f'"u" {a["WU"]}', f'"u" {b["WU"]}').replace(f'(words {a["WU"]})', f'(words {b["WU"]})')
    out = out.replace(f'"v" {a["WV"]}', f'"v" {b["WV"]}').replace(f'(words {a["WV"]})', f'(words {b["WV"]})')
    out = out.replace(f'vect_compare_spec {a["NB"]}', f'vect_compare_spec {b["NB"]}')
    out = out.replace(f'vect_compare_spec {a["VB"]}', f'vect_compare_spec {b["VB"]}')
    out = out.replace(f'"c" {a["CT"]}', f'"c" {b["CT"]}')
    if b['K'] == 32:
        out = out.replace('    xk <- llvm_unsafe_assume_spec m "xof_get_bytes" (xof_get_spec 32);\n', '')
        out = out.replace('let OV = [xi, x32, xk,', 'let OV = [xi, x32,')
    out += (f'print "VERIFIED: v5.1.0 hqc-{p} hqc_kem_decaps == decaps (implicit rejection); '
            f'vect_compare proved at {b["NB"]}, {b["VB"]}, 16";\n')
    return '// GENERATED by scripts/hqc_decaps_gen.py from decaps51_1.saw; do not edit.\n' + out


def main():
    check = '--check' in sys.argv
    cry = open(f'{ROOT}/model/cryptol/hqc-decaps/Decaps1.cry').read()
    saw = open(f'{ROOT}/proof/hqc-decaps/decaps_1.saw').read()
    cry51 = open(f'{ROOT}/model/cryptol/hqc-decaps/DecapsV51_1.cry').read()
    saw51 = open(f'{ROOT}/proof/hqc-decaps/decaps51_1.saw').read()
    bad = 0
    jobs = []
    for p in (3, 5):
        jobs.append((f'{ROOT}/model/cryptol/hqc-decaps/DecapsV51_{p}.cry', subst_cry51(cry51, p)))
        jobs.append((f'{ROOT}/proof/hqc-decaps/decaps51_{p}.saw', subst_saw51(saw51, p)))
    for path, text in jobs:
        if check:
            if not os.path.exists(path) or open(path).read() != text:
                print(f'!! stale: {os.path.relpath(path, ROOT)} (run scripts/hqc_decaps_gen.py)')
                bad = 1
        else:
            open(path, 'w').write(text)
    for p in (3, 5):
        for path, text in ((f'{ROOT}/model/cryptol/hqc-decaps/Decaps{p}.cry', subst_cry(cry, p)),
                           (f'{ROOT}/proof/hqc-decaps/decaps_{p}.saw', subst_saw(saw, p))):
            if check:
                if not os.path.exists(path) or open(path).read() != text:
                    print(f'!! stale: {os.path.relpath(path, ROOT)} (run scripts/hqc_decaps_gen.py)')
                    bad = 1
            else:
                open(path, 'w').write(text)
    sys.exit(bad)


if __name__ == '__main__':
    main()
