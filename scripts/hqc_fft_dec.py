#!/usr/bin/env python3
"""Generate proof/hqc-fft/r3_dec.saw and r5_dec.saw: decode_64 at 1024 and 2048 elements, proved in parts
of 32 batches. Batch i writes output bytes i + step * (8 kb + jj) (step = n/8), so a part [i0, i0 + 32)
owns the 64 runs of 32 bytes at offsets i0 + step * t, t < 64; dbytes<p> x i0 t (FFTEnc.cry) is that run.
Every part goes through dec_pre of specs.saw, the setup and call that dec_spec uses, and states its runs
on a byte view of the same allocation. dbytes<p>_cover (make hqc-fft-lemmas) proves each run equal to the
bytes of decode<p> x at those offsets, and the parts' offsets cover the whole output once (checked below).
Usage: hqc_fft_dec.py [--check]   (--check: fail if the committed files differ from the generated ones)."""
import sys, pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
HDR = """// GENERATED by scripts/hqc_fft_dec.py; do not edit. Additive-FFT reference, hqc-{p}: decode_64 at {n}
// elements against decode{p} (FFTEnc.cry), proved in {parts} parts of 32 batches (A-HQC-FFT item 8). Output
// byte i + {step} (8 kb + jj) comes from batch i, so a part [i0, i0 + 32) owns the 64 runs of 32 bytes at
// offsets i0 + {step} t, t < 64 (dbytes{p} x i0 t); each part's goal depends on its 256 input words only.
// One obligation for the whole output needed more than 45 GB under rme at hqc-5; a part takes about
// 13 GB. Every part uses dec_pre of specs.saw (the setup and call of dec_spec), with no slack: the
// bitcode has the repaired decode_64 (item 7). Each part has a mutant (its first run flipped).
import "FFTRef.cry";
import "FFTEnc.cry";
m <- llvm_load_module "../../build/hqc-fft/fft_ref.bc";
include "specs.saw";
tr <- llvm_verify m "transpose_8x8" [] false (tr_spec (\\x -> {{{{ transpose8 x }}}})) (w4_unint_z3 []);
fails (llvm_verify m "transpose_8x8" [] false (tr_spec (\\x -> {{{{ transpose8 x ^ [1, 0, 0, 0, 0, 0, 0, 0] }}}})) (w4_unint_z3 []));
"""

def gen(p, n):
    step, parts = n // 8, n // 256
    out = [HDR.format(p=p, n=n, parts=parts, step=step)]
    seen = set()
    for k in range(parts):
        i0 = 32 * k
        for mut in (False, True):
            name = f'dec{p}_part{k}' + ('_mut' if mut else '')
            out.append(f'let {name} = do {{\n  (rp, x) <- dec_pre {n} 0 {{{{ {n} : [32] }}}};\n'
                       f'  let rb = llvm_cast_pointer rp (llvm_array {8 * n} (llvm_int 8));\n')
            for t in range(64):
                off = i0 + step * t
                if not mut:
                    seen.update(range(off, off + 32))
                term = f'dbytes{p} x {i0} {t}' + (' ^ ([1] # zero)' if mut and t == 0 else '')
                out.append(f'  llvm_points_to_untyped (llvm_elem rb {off}) (llvm_term {{{{ {term} }}}});\n')
            out.append('};\n')
        out.append(f'p{k} <- llvm_verify m "decode_64" [tr] false dec{p}_part{k} rme;\n'
                   f'fails (llvm_verify m "decode_64" [tr] false dec{p}_part{k}_mut rme);\n')
    assert seen == set(range(8 * n)), f'hqc-{p}: the runs do not cover the {8 * n} output bytes'
    out.append(f'print "VERIFIED: hqc-{p} decode_64({n}) == decode{p}, in {parts} parts of 32 batches";\n')
    return ''.join(out)

def main():
    check = '--check' in sys.argv
    bad = 0
    for p, n in ((3, 1024), (5, 2048)):
        path = ROOT / f'proof/hqc-fft/r{p}_dec.saw'
        txt = gen(p, n)
        if check:
            if path.read_text() != txt:
                print(f'!! {path.relative_to(ROOT)} is stale; run scripts/hqc_fft_dec.py'); bad = 1
        else:
            path.write_text(txt)
    if check and not bad:
        print('OK: r3_dec.saw and r5_dec.saw match the generator; the runs cover every output byte once')
    sys.exit(bad)

if __name__ == '__main__':
    main()
