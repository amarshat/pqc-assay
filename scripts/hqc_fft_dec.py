#!/usr/bin/env python3
"""Generate the decode_64 contracts of the additive-FFT proofs at 1024 and 2048 elements.

Batch i of decode_64 writes output bytes i + step (8 kb + jj) (step = n/8), so the output is n/4 runs of
32 bytes: the run (i0, t), i0 a multiple of 32 below step and t < 64, is the bytes at offsets i0 + step t
and equals dbytes<p> x i0 t (FFTEnc.cry). The whole output as one SAW obligation needed more than 45 GB
under rme at hqc-5; stated run by run, each points-to is its own goal of 256 input words.

proof/hqc-fft/dec_runs.saw defines dec3_runs and dec5_runs: the setup and call of dec_pre (specs.saw) and
one llvm_points_to_untyped per run on a byte view of the output. r3_dec.saw / r5_dec.saw prove them with
llvm_verify, and fft_3.saw / fft_5.saw assume the same expressions, which scripts/hqc_fft_links.py checks.
asm<p> (FFTEnc.cry) is the same assembly as a Cryptol function; fft_<p> proves decode<p> == asm<p> by rme.
The generator asserts that the runs cover every output byte once.
Usage: hqc_fft_dec.py [--check]   (--check: fail if the committed files differ from the generated ones)."""
import sys, pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
SIZES = ((3, 1024), (5, 2048))

RUNS_HDR = """// GENERATED by scripts/hqc_fft_dec.py; do not edit. Included after specs.saw by r3_dec, r5_dec, fft_3, fft_5
// (it needs FFTEnc.cry). decode_64 at 1024 and 2048
// elements as one contract stated in runs: output byte i + step t (step = n/8, i < step) is byte i % 32
// of dbytes<p> x (i - i % 32) t, so the output is n/4 runs of 32 bytes, each its own points-to on a byte
// view of the dec_pre allocation. f is applied to the first run only (the identity for the proof, a bit
// flip for the mutant). asm<p> (FFTEnc.cry) is the same assembly as a Cryptol function.
"""

DEC_HDR = """// GENERATED by scripts/hqc_fft_dec.py; do not edit. Additive-FFT reference, hqc-{p}: decode_64 at {n}
// elements against the runs of decode{p} (dec{p}_runs of dec_runs.saw, A-HQC-FFT item 8), one obligation
// per 32-byte run, with transpose_8x8 as an override. No slack: the bitcode has the repaired decode_64
// (item 7). The mutant flips one bit of the first run.
import "FFTRef.cry";
import "FFTEnc.cry";
m <- llvm_load_module "../../build/hqc-fft/fft_ref.bc";
include "specs.saw";
include "dec_runs.saw";
tr <- llvm_verify m "transpose_8x8" [] false (tr_spec (\\x -> {{{{ transpose8 x }}}})) (w4_unint_z3 []);
fails (llvm_verify m "transpose_8x8" [] false (tr_spec (\\x -> {{{{ transpose8 x ^ [1, 0, 0, 0, 0, 0, 0, 0] }}}})) (w4_unint_z3 []));
d{p} <- llvm_verify m "decode_64" [tr] false (dec{p}_runs (\\r -> r)) rme;
fails (llvm_verify m "decode_64" [tr] false (dec{p}_runs (\\r -> {{{{ r ^ ([1] # zero) }}}})) rme);
print "VERIFIED: hqc-{p} decode_64({n}) == the {runs} runs of decode{p}";
"""

def runs(p, n):
    step = n // 8
    out = [f'let dec{p}_runs f = do {{\n  (rp, x) <- dec_pre {n} 0 {{{{ {n} : [32] }}}};\n'
           f'  let rb = llvm_cast_pointer rp (llvm_array {8 * n} (llvm_int 8));\n']
    seen = set()
    for i0 in range(0, step, 32):
        for t in range(64):
            off = i0 + step * t
            assert not seen & set(range(off, off + 32))
            seen.update(range(off, off + 32))
            term = f'{{{{ dbytes{p} x {i0} {t} }}}}'
            if i0 == 0 and t == 0:
                term = f'(f {term})'
            out.append(f'  llvm_points_to_untyped (llvm_elem rb {off}) (llvm_term {term});\n')
    assert seen == set(range(8 * n)), f'hqc-{p}: the runs do not cover the {8 * n} output bytes'
    out.append('  mats_post;\n};\n')
    return ''.join(out)

def files():
    yield 'proof/hqc-fft/dec_runs.saw', RUNS_HDR + ''.join(runs(p, n) for p, n in SIZES)
    for p, n in SIZES:
        yield f'proof/hqc-fft/r{p}_dec.saw', DEC_HDR.format(p=p, n=n, runs=n // 4)

def main():
    check = '--check' in sys.argv
    bad = 0
    for rel, txt in files():
        path = ROOT / rel
        if check:
            if not path.exists() or path.read_text() != txt:
                print(f'!! {rel} is stale; run scripts/hqc_fft_dec.py'); bad = 1
        else:
            path.write_text(txt)
    if check and not bad:
        print('OK: dec_runs.saw, r3_dec.saw and r5_dec.saw match the generator; the runs cover every output byte once')
    sys.exit(bad)

if __name__ == '__main__':
    main()
